import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

// Usage: node scripts/import-tank-a-levels.mjs /path/to/tank1990.nes
// Only this verified revision is accepted; the ROM is not shipped with the game.
const source =
  'https://github.com/infoplat/jsnes/blob/7a12133e3095b84cfc312f0f227fc5dba0fb74f4/roms/rom1/(Ch)%20Tank%201990.nes'
const sha256 = 'ec453e7e3cc1d49d11d5860ced7f9e1235e2c7d33927bd6073b631754dc08dbb'
if (!process.argv[2]) throw new Error('Pass the path to the verified Tank 1990 ROM')
const rom = await readFile(process.argv[2])
if (createHash('sha256').update(rom).digest('hex') !== sha256)
  throw new Error('Unsupported ROM revision; no files were written')

// Mode A: $46 = 0, table $E42B = $F030 / 12 base maps.
// $EF76 reads 13 rows of packed nibbles, with a padding nibble per row.
// Each 12-stage loop advances the data pointer by 2 bytes, modulo 6 ($D34D).
// This is a byte-offset transformation across rows, NOT a horizontal row rotation.
// Stage selector $C195/$C199 and $C627/$C62F permits stages 1–50.
// Tile geometry is unchanged from Battle City ($DACB).
const glyphs = '>v<^#rblt@~*%...'
const maps = Array.from({ length: 50 }, (_, stage) => {
  const pointer = 16 + 0xf030 - 0x8000 + (stage % 12) * 91 + ((Math.floor(stage / 12) * 2) % 6)
  return Array.from({ length: 13 }, (_, y) =>
    Array.from({ length: 13 }, (_, x) => {
      const byte = rom[pointer + y * 7 + Math.floor(x / 2)]
      return glyphs[(byte >> (x % 2 === 0 ? 4 : 0)) & 15]
    }).join(''),
  )
})
const hash = createHash('sha256').update(maps.flat().join('\n')).digest('hex')
const text = `/**
 * Tank 1990, Tank A selectable stages 1–50 (36 distinct layouts, then repeats).
 * Source: ${source}
 * ROM SHA256: ${sha256}
 * Decoded terrain SHA256: ${hash}
 * Generated by scripts/import-tank-a-levels.mjs; see that script for ROM addresses.
 * Decoding independently checked against execution of the ROM's 6502 map routine.
 * Maps only: enemy waves and combat rules use this web game's existing rules.
 */
export const TANK_A_TERRAINS: readonly (readonly string[])[] = [
${maps.map((rows, i) => `  // STAGE ${String(i + 1).padStart(2, '0')}\n  [\n${rows.map((row) => `    '${row}',`).join('\n')}\n  ],`).join('\n')}
]
`
await writeFile(new URL('../src/games/tank-battle/data/tankA.ts', import.meta.url), text)
console.log(`Imported ${maps.length} stages; terrain SHA256 ${hash}`)
