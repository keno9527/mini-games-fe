export const PUZZLE_LEVELS: readonly PuzzleLevel[] = definitions.map(
  ([name, moves, blackText, whiteText, hint, explanation], index) => {
    const black = blackText.split(' ')
    const white = whiteText.split(' ')
    return {
      id: index + 1,
      name,
      moves,
      black,
      white,
      hint,
      explanation,
      board: makeBoard(black, white),
    }
  },
)
