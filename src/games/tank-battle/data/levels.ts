const ENEMY_KINDS = [EnemyKind.BASIC, EnemyKind.FAST, EnemyKind.POWER, EnemyKind.ARMOR] as const
function stage(terrain: readonly string[], wave: string): LevelData {
  return { terrain, enemyQueue: [...wave].map((kind) => ENEMY_KINDS[Number(kind)]) }
}

