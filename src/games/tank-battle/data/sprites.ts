/** 履带第二帧只交换相邻履带像素，保留车身轮廓与透明边缘。 */
function treadFrame(up: readonly string[]): readonly string[] {
  return up.map((row, y) =>
    [...row]
      .map((pixel, x) => {
        if (x > 3 && x < 11) return pixel
        const neighbor = up[y % 2 === 0 ? y + 1 : y - 1]?.[x]
        return pixel !== ' ' && neighbor && neighbor !== ' ' ? neighbor : pixel
      })
      .join(''),
  )
}
